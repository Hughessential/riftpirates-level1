def pack(fmt,*v):return struct.pack('>'+fmt,*v)
def checksum(b):
 b+=b'\0'*((-len(b))%4)
 return sum(struct.unpack('>'+str(len(b)//4)+'I',b))&0xffffffff

chars=sorted(patterns,key=ord)
glyphs=['?']+chars
glyf=b''; offsets=[]; maxpts=0; maxcont=0
for char in glyphs:
 offsets.append(len(glyf)); points=[]; ends=[]
 for row,bits in enumerate(patterns[char].split('/')):
  x=0
  while x<5:
   if bits[x]=='0':x+=1;continue
   end=x+1
   while end<5 and bits[end]=='1':end+=1
   left=40+x*100; right=40+end*100; bottom=(6-row)*100
   points += [(left,bottom),(left,bottom+100),(right,bottom+100),(right,bottom)]
   ends.append(len(points)-1);x=end
 maxpts=max(maxpts,len(points));maxcont=max(maxcont,len(ends))
