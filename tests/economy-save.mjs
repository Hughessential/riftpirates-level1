import assert from 'node:assert/strict';
const key = 'riftpirates-level1-v1';
const saved = new Map([[key,JSON.stringify({ scrapBanked:12345,bestScore:9000,runs:8,clears:2,musicVolume:.74,sfxVolume:.83,selectedShip:'rift-talon' })]]);
globalThis.window = { localStorage: { getItem:k=>saved.get(k)||null,setItem:(k,v)=>saved.set(k,v) } };
const { Save } = await import('../src/core/SaveSystem.js');
Save.load();
assert.equal(Save.data.scrapBanked,12345); assert.equal(Save.data.musicVolume,.74);
const run={runId:'economy-save-test',scrap:170,score:100,time:99,grade:'D',cleared:false};
assert.equal(Save.bankRun(run),true);
assert.equal(Save.data.scrapBanked,12515); assert.equal(Save.data.runs,9);
assert.equal(Save.bankRun(run),false); assert.equal(Save.data.scrapBanked,12515);
assert.equal(Save.data.bestScore,9000); assert.equal(Save.data.selectedShip,'rift-talon');
Save.load(); assert.equal(Save.bankRun(run),false,'Reload retains duplicate-bank protection');
Save.bankRun({...run,runId:'victory-test',scrap:0,cleared:true});
assert.equal(Save.data.scrapBanked,12515); assert.equal(Save.data.clears,3);
window.localStorage={getItem(){throw Error('blocked')},setItem(){throw Error('blocked')}};
Save.bankRun({...run,runId:'private-storage',scrap:9});
const expected=Save.data.scrapBanked;
Save.data.scrapBanked=0; Save.load(); assert.equal(Save.data.scrapBanked,expected,'Blocked storage retains memory fallback');
console.log('PASS: old saves retain bank/settings, only remainder banks, death/victory idempotency and blocked-storage fallback');
